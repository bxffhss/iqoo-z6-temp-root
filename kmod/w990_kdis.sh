0xfd 0xc3 0x01 0x91
0x68 0xd3 0x00 0xd0
0x08 0x9d 0x45 0xf9
0xf4 0x03 0x00 0xaa
0xf9 0x03 0x02 0xaa
0xa8 0x83 0x1f 0xf8
0x68 0xd3 0x00 0xd0
0x00 0xd5 0x47 0xf9
EOF
echo "=== security_load_policy 前 16 条(设备真身) ==="
$MC -triple=aarch64 -disassemble < /tmp/w990_security_load_policy.txt 2>&1 | sed -n "1,20p"
cat > /tmp/w990_security_context_to_sid.txt <<'EOF'
0x5e 0x86 0x00 0xf8
0xfd 0x7b 0xbf 0xa9
