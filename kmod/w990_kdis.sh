0xfd 0x7b 0x06 0xa9
0xf8 0x5f 0x07 0xa9
0xf6 0x57 0x08 0xa9
0xf4 0x4f 0x09 0xa9
EOF
echo "=== security_context_to_sid 前 16 条(设备真身) ==="
$MC -triple=aarch64 -disassemble < /tmp/w990_security_context_to_sid.txt 2>&1 | sed -n "1,20p"
