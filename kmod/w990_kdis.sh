#!/bin/bash
# w990：把从**设备自己那份 Image** 按 vaddr 抠出的指令喂 llvm-mc，读参数约定(不是读头的声明)。
# 生成方式＝kmod/w989_ktext.py hex；出处＝analysis/kernel_dev_g2a88cd145def.bin ＋ 设备 kallsyms。
# ★llvm-mc -disassemble 只吃 `0xff 0x83 0x01 0xd1`(内存序、每字节带 0x)。裸字节/裸 word/带 .text 头 三种写法都报 invalid input token(一手试的)。
set -u
MC=llvm-mc
command -v $MC >/dev/null || { echo '!! 没有 llvm-mc ⇒ 这格记未测，不许凭眼看 hex 下结论'; exit 1; }
cat > /tmp/w990_security_read_policy.txt <<'EOF'
0xff 0x83 0x01 0xd1
0x5e 0x86 0x00 0xf8
0xfd 0x7b 0x02 0xa9
0xf7 0x1b 0x00 0xf9
0xf6 0x57 0x04 0xa9
0xf4 0x4f 0x05 0xa9
0xfd 0x83 0x00 0x91
0x68 0xd3 0x00 0x90
0x08 0x9d 0x45 0xf9
0xa8 0x83 0x1f 0xf8
0x17 0x0c 0x40 0xf9
0xff 0xff 0x00 0xa9
0x08 0x0c 0x40 0x39
0x48 0x04 0x00 0x34
0xf5 0x03 0x00 0xaa
0xe0 0xe2 0x07 0x91
EOF
echo "=== security_read_policy 前 16 条(设备真身) ==="
$MC -triple=aarch64 -disassemble < /tmp/w990_security_read_policy.txt 2>&1 | sed -n "1,20p"
cat > /tmp/w990_security_load_policy.txt <<'EOF'
0xff 0x43 0x03 0xd1
0x5e 0x86 0x00 0xf8
0xfd 0x7b 0x07 0xa9
0xfb 0x43 0x00 0xf9
0xfa 0x67 0x09 0xa9
