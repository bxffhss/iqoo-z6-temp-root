# blank_gate.sh —— "空枪"判据的**唯一真源**：`kmod/go.sh` 与 `kmod/w380_blankgate_selftest.sh` 都 source 这里。
#   为什么要抽出来(§6.290)：夹具原来把谓词**抄了一份**，那意味着以后有人改 go.sh 的判据，自测照样全绿 ⇒ 假保险(例 93/89)。
#   现在两边共用同一个函数，**漂移在结构上不可能**。
# blank_now <sawper(0/1)> <getenforce 现值> <pr 的 pid 串(空=不在)> <[POST] 计数(字符串)>
#   ⇒ 返回 0 = 允许计一次"空枪确认"；非 0 = 继续等(等满 17 分钟)。
#   三段闩锁的含义：①本 boot **确实见过 Permissive**(＝翻转真发生过，纯 ASCII 信号，不去匹配带 CJK 的翻转行)；
#   ②现在**已回到 Enforcing**(§6.119：生效位被人写回 1 ⇒ 这发确实做不下去，比 `pidof pr` 可靠)；
#   ③`pr` 不在且 `[POST]` 计数为 0。旧规则只看"有 [SEN] 无 [POST]"，而 `[SEN]` 含**翻转之前**那两行 ⇒ 135 发因此误判。
blank_now() {
    [ -z "$3" ] && [ "$1" = 1 ] && [ "$2" = Enforcing ] && [ "$4" = "0" ]
}
